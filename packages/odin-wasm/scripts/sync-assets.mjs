// Copies the assets the repository builds into this package, and rewrites
// `src/asset-receipts.js` to pin them.
//
//   npm run sync-assets        (from this package)
//   npm run assets:package     (from the repository root, which builds first)
//
// The repository's `scripts/build-assets.sh` builds `assets/odin.wasm` and
// `assets/odin-src.pack.gz` at the root; a package has to carry its own copy, so
// this is the one step between them.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const ROOT_ASSETS = new URL('../../../assets/', import.meta.url);
const PUBLIC = new URL('../../../public/', import.meta.url);
const PACKAGE_ASSETS = new URL('../assets/', import.meta.url);
const RECEIPTS = new URL('../src/asset-receipts.js', import.meta.url);

// What ships in assets/, in the order the package loads it, and where each comes from.
const ASSETS = [
  ['odin.wasm', new URL('odin.wasm', ROOT_ASSETS)],
  ['odin-src.pack.gz', new URL('odin-src.pack.gz', ROOT_ASSETS)],
  // Odin's own JS runtime, which is what a js_wasm32 program runs on when it needs the DOM — a
  // worker has no `document`, so the host instantiates on the page. The repository vendors it for
  // its own page; this is the same file.
  ['odin.js', new URL('odin.js', PUBLIC)],
];

await mkdir(PACKAGE_ASSETS, { recursive: true });

const receipts = [];
for (const [name, from] of ASSETS) {
  await copyFile(from, new URL(name, PACKAGE_ASSETS));
  const bytes = await readFile(new URL(name, PACKAGE_ASSETS));
  receipts.push({
    name,
    bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
  });
}

const entries = receipts
  .map(({ name, bytes, sha256 }) => `\t'${name}': Object.freeze({ bytes: ${bytes}, sha256: '${sha256}' })`)
  .join(',\n');

const body = `// Receipts for the assets this package ships in \`assets/\`, keyed by their path under it.
//
// Generated by scripts/sync-assets.mjs — do not edit by hand.
//
// Every read is checked against one of these before the bytes are used, so a truncated download or
// a host serving something else is an error here rather than a wasm instantiation failure a step
// later.

export const ASSET_RECEIPTS = Object.freeze({
${entries}
});
`;

await writeFile(RECEIPTS, body);

for (const { name, bytes } of receipts) {
  console.log(`  ${name}  ${bytes} bytes`);
}
console.log(`Wrote assets/ and src/asset-receipts.js`);
